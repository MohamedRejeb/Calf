package com.mohamedrejeb.calf.sample.ui.theme

import androidx.compose.ui.unit.dp

/** The sample's spacing scale. Every demo page uses these, never its own numbers. */
object Spacing {
    val xs = 4.dp
    val s = 8.dp
    val m = 12.dp
    val l = 16.dp
    val xl = 24.dp
    val xxl = 32.dp

    /** Horizontal margin of a page and of the home list. */
    val pageMargin = 16.dp

    /** Space between the sections of a page. */
    val sectionGap = 28.dp
}

/** Content wider than this reads badly; a demo page centres itself on desktop and tablets. */
val PageMaxWidth = 680.dp

/** Size of the rounded square behind an icon in a list row. */
val IconTileSize = 32.dp
